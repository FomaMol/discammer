#!/usr/bin/env bash
set -euo pipefail

# =============================================================================
# gen-cf-real-ip.sh — regenerate deploy/nginx/cloudflare-real-ip.conf (CF-8)
# =============================================================================
# Fetches the current Cloudflare edge IP ranges and rewrites the nginx
# `set_real_ip_from` include so $remote_addr is restored to the real visitor IP
# behind Cloudflare's proxy. Cloudflare publishes the canonical lists at
# https://www.cloudflare.com/ips-v4 and /ips-v6. The ranges change rarely, so
# this is a maintenance script — run it occasionally (or from cron), then
# REVIEW + COMMIT the regenerated file so REL-3 ships it to the host on deploy.
#
# It does NOT touch the live host config directly (that path is deploy.sh →
# nginx -t → reload). Keeping generation and application separate means a bad
# upstream fetch can never silently land on prod without a commit + review.
#
# Idempotent: same upstream ranges → byte-identical output (sorted/stable).
#
# Usage:
#   scripts/gen-cf-real-ip.sh                 # rewrite the committed conf
#   OUT=/tmp/x.conf scripts/gen-cf-real-ip.sh # write elsewhere (dry test)
# =============================================================================

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${OUT:-$repo_root/deploy/nginx/cloudflare-real-ip.conf}"

V4_URL="https://www.cloudflare.com/ips-v4"
V6_URL="https://www.cloudflare.com/ips-v6"

fetch() {
  # Fail loudly on a bad fetch — never emit a partial/empty allow list.
  local url="$1"
  curl -fsSL --max-time 20 "$url" | grep -E '^[0-9a-fA-F:.]+/[0-9]+$' || {
    echo "ERROR: failed to fetch or parse $url" >&2
    return 1
  }
}

v4="$(fetch "$V4_URL")"
v6="$(fetch "$V6_URL")"

if [ -z "$v4" ] || [ -z "$v6" ]; then
  echo "ERROR: empty IP range list — refusing to write $OUT" >&2
  exit 1
fi

today="$(date -u +%Y-%m-%d)"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  cat <<'HEADER'
# =============================================================================
# Cloudflare real-IP restoration (CF-8)
# =============================================================================
# When Cloudflare proxies the site, every request reaches the origin from a CF
# edge IP. Without this file nginx logs, $remote_addr, X-Real-IP and the app's
# per-IP rate limiter would all collapse to "some Cloudflare address" instead of
# the real visitor — breaking abuse mitigation and forensics.
#
# `set_real_ip_from <cidr>` tells nginx to TRUST the CF-Connecting-IP header from
# those peers and rewrite $remote_addr to the real client. We use CF-Connecting-IP
# (Cloudflare's authoritative single client IP) rather than X-Forwarded-For so a
# spoofed XFF from a non-CF source can never poison the value: the trust is gated
# on the peer being in a Cloudflare range AND the header CF itself sets.
#
# SECURITY: this is only safe in tandem with CF-8's firewall (scripts/cf-firewall.sh)
# which DROPs :443 from everything except these same ranges. If the origin were
# reachable directly, an attacker could connect from a spoofed source and send a
# forged CF-Connecting-IP. Firewall + real_ip together close that hole.
#
# `include`d from the apex server block in discammer.conf.
#
# Generated by scripts/gen-cf-real-ip.sh from https://www.cloudflare.com/ips-v4
# and /ips-v6. Ranges change rarely; refresh with that script and re-commit.
HEADER
  echo "# Last refreshed: $today"
  echo "# -----------------------------------------------------------------------------"
  echo
  echo "# --- Cloudflare IPv4 ---"
  while IFS= read -r cidr; do [ -n "$cidr" ] && echo "set_real_ip_from $cidr;"; done <<< "$v4"
  echo
  echo "# --- Cloudflare IPv6 ---"
  while IFS= read -r cidr; do [ -n "$cidr" ] && echo "set_real_ip_from $cidr;"; done <<< "$v6"
  echo
  cat <<'FOOTER'
# Use Cloudflare's authoritative client-IP header. CF strips any inbound
# CF-Connecting-IP from the client and sets its own, so this is trustworthy
# from a CF peer. real_ip_recursive is intentionally OFF — CF-Connecting-IP is
# already the single real client, no chain to walk.
real_ip_header CF-Connecting-IP;
FOOTER
} > "$tmp"

mv "$tmp" "$OUT"
trap - EXIT
echo "Wrote $OUT ($(grep -c set_real_ip_from "$OUT") Cloudflare ranges). Review + commit the change."
